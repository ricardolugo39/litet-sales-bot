"""Build offline HTML pages from the canvas source in ./source.

    python3 design/decision-center-handoff/prototype/build.py

Reads source/Main.dc.html and source/Handoff.dc.html and writes
standalone/index.html and standalone/handoff.html. Uses only the
standard library. Run it again after editing the .dc.html source.
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE / "source"
OUT = HERE / "standalone"


def parts(text):
    body = re.search(r"<x-dc>(.*)</x-dc>", text, re.S).group(1)
    style = re.search(r"<helmet>\s*<style>(.*?)</style>\s*</helmet>", body, re.S)
    css = style.group(1) if style else ""
    body = re.sub(r"<helmet>.*?</helmet>", "", body, flags=re.S)
    body = re.sub(r"<sc-if\b", "<template data-if", body)
    body = re.sub(r"</sc-if>", "</template>", body)
    body = re.sub(r"<sc-for\b", "<template data-for", body)
    body = re.sub(r"</sc-for>", "</template>", body)
    script = re.search(r"<script type=\"text/x-dc\"[^>]*>(.*?)</script>", text, re.S).group(1)
    title = re.search(r"<title>(.*?)</title>", text, re.S).group(1)
    return title, css, body, script


PAGE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<title>{title}</title>
<!-- Generated by build.py from source/{src}. Edit the source, then rebuild. -->
<style>{css}</style>
</head>
<body>
<div id="root"></div>
<template id="dc-template">{body}</template>
<script src="dc-lite.js"></script>
<script>{script}</script>
<script>
(function () {{
  var q = new URLSearchParams(location.search);
  var props = {{}};
  ['scenario', 'dataState', 'startPage'].forEach(function (k) {{ if (q.get(k)) props[k] = q.get(k); }});
  if (q.get('narrow') === '1') props.narrow = true;
  dcLite.mount({{ templateId: 'dc-template', rootId: 'root', Component: Component, props: props }});
}})();
</script>
</body>
</html>
"""


def build(src, dest):
    title, css, body, script = parts((SRC / src).read_text(encoding="utf-8"))
    (OUT / dest).write_text(PAGE.format(title=title, css=css, body=body, script=script, src=src), encoding="utf-8")
    print("wrote", OUT / dest)


if __name__ == "__main__":
    OUT.mkdir(exist_ok=True)
    build("Main.dc.html", "index.html")
    build("Handoff.dc.html", "handoff.html")
